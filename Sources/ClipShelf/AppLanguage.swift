func L(_ key: String, _ arguments: Any...) -> String {
    let template = AppLocalization.text(key, language: AppLocalization.shared.language)
    guard !arguments.isEmpty else { return template }
    return String(format: template, arguments: arguments.map { String(describing: $0) as NSString })
}
