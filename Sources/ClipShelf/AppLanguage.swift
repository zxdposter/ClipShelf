enum AppLanguage: String, CaseIterable, Identifiable {
    case chinese = "zh-Hans", english = "en"
    var id: Self { self }
    var title: String { self == .chinese ? "中文" : "English" }
    static func initial(preferredLanguages: [String]) -> Self {
        let code = preferredLanguages.first?.replacingOccurrences(of: "_", with: "-").lowercased().split(separator: "-").first
        return code == "zh" ? .chinese : .english
    }
}

